using System.Text.Json.Serialization;

namespace PNMTD.Models.Enums;

// The UDP nodes' settings and states (docs/udp-iot-plan.md §4.3). Stored as smallint; strings in /api/v1.

/// <summary>When PNMTD sends an ACK (§3.9). A COMMAND or an OTA_OFFER in the response replaces it.</summary>
[JsonConverter(typeof(JsonStringEnumConverter<UdpAckMode>))]
public enum UdpAckMode : short { Never = 0, OnRequest = 1, Always = 2 }

/// <summary>None: the root key and a persistent counter. JoinRequired: a JOIN at every start (§3.8).</summary>
[JsonConverter(typeof(JsonStringEnumConverter<UdpSessionMode>))]
public enum UdpSessionMode : short { None = 0, JoinRequired = 1 }

/// <summary>Generated by PNMTD, or entered by a user (§4.3).</summary>
[JsonConverter(typeof(JsonStringEnumConverter<UdpSecretSource>))]
public enum UdpSecretSource : short { Generated = 0, Manual = 1 }

/// <summary>§4.6.</summary>
[JsonConverter(typeof(JsonStringEnumConverter<UdpCommandState>))]
public enum UdpCommandState : short { Queued = 0, Sent = 1, Completed = 2, Failed = 3, Expired = 4, Cancelled = 5 }

/// <summary>§3.10.</summary>
[JsonConverter(typeof(JsonStringEnumConverter<UdpCommandDelivery>))]
public enum UdpCommandDelivery : short { ResultRequired = 0, FireAndForget = 1 }

/// <summary>A step of a command or an update, as <c>udp_command_log</c> records it (§4.3).</summary>
[JsonConverter(typeof(JsonStringEnumConverter<UdpLogKind>))]
public enum UdpLogKind : short
{
    Queued = 0,
    Sent = 1,
    Resent = 2,
    ResultReceived = 3,
    UnmatchedResult = 4,
    Cancelled = 5,
    Expired = 6,
    Failed = 7,
    OtaQueued = 20,
    OtaOffered = 21,
    OtaStarted = 22,
    OtaDeclined = 23,
    OtaVerified = 24,
    OtaFailed = 25,
    OtaApplied = 26,
    OtaCancelled = 27,
    OtaExpired = 28,
}

[JsonConverter(typeof(JsonStringEnumConverter<UdpDirection>))]
public enum UdpDirection : short { Up = 0, Down = 1 }

/// <summary>§4.11.</summary>
[JsonConverter(typeof(JsonStringEnumConverter<UdpOtaState>))]
public enum UdpOtaState : short
{
    Queued = 0,
    Offered = 1,
    Downloading = 2,
    Verified = 3,
    Applied = 4,
    Declined = 5,
    Failed = 6,
    Cancelled = 7,
    Expired = 8,
}

/// <summary>Why the listener dropped a datagram (§4.5): counted, and for known nodes kept in memory.</summary>
[JsonConverter(typeof(JsonStringEnumConverter<UdpRejectReason>))]
public enum UdpRejectReason : short
{
    Malformed = 0,
    WrongDirection = 1,
    UnknownDevice = 2,
    Disabled = 3,
    SuiteNotAllowed = 4,
    SessionRequired = 5,
    RateLimited = 6,
    BadTag = 7,
    Replay = 8,
    CounterJump = 9,
    QueueFull = 10,
    Error = 11,
}

public static class UdpEnumExtensions
{
    public static bool IsOpen(this UdpCommandState state) => state is UdpCommandState.Queued or UdpCommandState.Sent;

    public static bool IsOpen(this UdpOtaState state) => state is UdpOtaState.Queued or UdpOtaState.Offered or UdpOtaState.Downloading or UdpOtaState.Verified;
}
